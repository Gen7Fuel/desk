const crypto = require('node:crypto')
const bookworks = require('./bookworks.service')
const { configuredSage, ENTITY } = require('./bookworks.sage')
const error = (message, status = 400) => Object.assign(new Error(message), { status })
const hash = value => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex')

function cents(value) {
  if (typeof value !== 'number' || !Number.isFinite(value) || Math.abs(value * 100 - Math.round(value * 100)) > 0.00001 || !Number.isSafeInteger(Math.round(value * 100))) {
    throw error('The invoice contains an invalid monetary amount.')
  }
  return Math.round(value * 100)
}
function calendarDate(value) {
  const date = typeof value === 'string' ? value.slice(0, 10) : ''
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || !Number.isFinite(Date.parse(date)) || new Date(date).toISOString().slice(0, 10) !== date) throw error('The Bookworks invoice or due date is invalid.')
  return date
}

function buildPreview(invoice, vendor, cogsType) {
  if (invoice.posted !== true) throw error('Only posted Bookworks invoices can be sent to Intacct.')
  if (!['fuel', 'freight'].includes(cogsType)) throw error('Select Fuel or Freight.')
  if (!vendor?.id) throw error('Save an Intacct vendor mapping first.')
  const totalCents = cents(invoice.totalAmount)
  if (totalCents <= 0) throw error('Only positive AP invoices are supported by this draft flow.')
  if (!invoice.distributions.length) throw error('The invoice has no GL distributions to reconcile.')
  let hstCents = 0, distributionCents = 0
  for (const line of invoice.distributions) {
    const direction = String(line.debitOrCredit || '').toUpperCase()
    if (!['D', 'DEBIT', 'C', 'CREDIT'].includes(direction)) throw error('A Bookworks distribution has an unknown debit/credit direction.')
    const amount = cents(line.amount)
    if (amount < 0) throw error('A Bookworks distribution has a negative amount. Review the invoice manually.')
    const signed = ['C', 'CREDIT'].includes(direction) ? -amount : amount
    distributionCents += signed
    if (String(line.glAccountCode).trim() === '22000') hstCents += signed
  }
  if (distributionCents !== totalCents) throw error('Bookworks distributions do not balance to the invoice total. Review the invoice before creating a draft.')
  const costCents = totalCents - hstCents
  if (hstCents < 0 || costCents <= 0) throw error('The HST or COGS amount is invalid. Review the invoice manually.')
  const preview = {
    invoiceId: invoice.id, invoiceNumber: invoice.invoiceNumber, entityId: ENTITY, company: 'Gen7 LP', currency: 'CAD',
    vendor, cogsType, cogsAccount: cogsType === 'fuel' ? '50200' : '51050',
    invoiceDate: calendarDate(invoice.invoiceDate), postingDate: calendarDate(invoice.invoiceDate), dueDate: calendarDate(invoice.dueDate),
    costCents, hstCents, totalCents,
  }
  preview.hash = hash({ invoice, preview })
  return preview
}

function buildBill(preview) {
  const lines = [{ account: preview.cogsAccount, cents: preview.costCents, memo: `COGS ${preview.cogsType}` }]
  if (preview.hstCents) lines.push({ account: '22000', cents: preview.hstCents, memo: 'HST from Bookworks GL 22000' })
  return {
    billNumber: preview.invoiceNumber, vendor: { id: preview.vendor.id },
    description: `Bookworks invoice ${preview.invoiceNumber}`, referenceNumber: `Bookworks #${preview.invoiceId}`,
    createdDate: preview.invoiceDate, postingDate: preview.postingDate, dueDate: preview.dueDate,
    state: 'draft', currency: { baseCurrency: 'CAD', txnCurrency: 'CAD' },
    isTaxInclusive: false, taxSolution: { key: '3' },
    // The AP credit is generated by Intacct using the vendor's default control
    // account. Adding an explicit AP line would duplicate that offset.
    lines: lines.map(line => ({
      glAccount: { id: line.account }, txnAmount: (line.cents / 100).toFixed(2),
      memo: `${preview.invoiceNumber}: ${line.memo}`, hasForm1099: 'false',
      dimensions: { location: { id: ENTITY }, vendor: { id: preview.vendor.id } },
      // HST is a manual GL 22000 debit, so don't have Intacct add tax again.
      taxEntries: [{ baseTaxAmount: '0', txnTaxAmount: '0', taxRate: 0, purchasingTaxDetail: { key: '69' } }],
    })),
  }
}

function createIntegration({ client, sage, repository, sourceKey } = {}) {
  const db = () => repository || require('./bookworks.model').repository
  const api = () => sage || configuredSage()
  const scope = () => ({ sourceKey: sourceKey || hash(new URL(process.env.BOOKWORKS_API_URL).href.replace(/\/$/, '')), entityId: ENTITY })
  const load = id => bookworks.loadInvoice(id, client)
  const mappingFilter = invoice => ({ ...scope(), vendorCode: invoice.vendorCode.trim().toUpperCase() })
  const entryFilter = id => ({ ...scope(), invoiceId: id })
  function publicEntry(entry) { return entry ? { status: entry.status, billKey: entry.billKey || null, entityId: ENTITY } : null }
  async function preview(id, cogsType, sageClient = api()) {
    const invoice = await load(id)
    if (invoice.posted !== true) throw error('Only posted Bookworks invoices can be sent to Intacct.')
    if (!['fuel', 'freight'].includes(cogsType)) throw error('Select Fuel or Freight.')
    if (!invoice.vendorCode) throw error('The Bookworks invoice has no vendor code.')
    const mapping = await db().getMapping(mappingFilter(invoice))
    if (!mapping) throw error('Save an Intacct vendor mapping first.')
    const vendor = await sageClient.getVendor(mapping.vendorId)
    return buildPreview(invoice, vendor, cogsType)
  }
  return {
    async context(id) {
      const invoice = await load(id)
      const [mapping, entry] = await Promise.all([
        invoice.vendorCode ? db().getMapping(mappingFilter(invoice)) : null,
        db().getEntry(entryFilter(id)),
      ])
      return { entityId: ENTITY, company: 'Gen7 LP', mapping: mapping ? { vendorId: mapping.vendorId, vendorName: mapping.vendorName } : null, entry: publicEntry(entry) }
    },
    async vendors(q) {
      if (typeof q !== 'string' || q.trim().length < 2 || q.trim().length > 100) throw error('Enter at least two characters of the Intacct vendor name.')
      return api().searchVendors(q.trim())
    },
    async saveMapping(id, vendorId, actor) {
      if (typeof vendorId !== 'string' || !vendorId.trim() || vendorId.length > 100) throw error('Select an Intacct vendor.')
      const invoice = await load(id)
      if (!invoice.vendorCode) throw error('The Bookworks invoice has no vendor code.')
      const vendor = await api().getVendor(vendorId.trim())
      await db().saveMapping(mappingFilter(invoice), { vendorId: vendor.id, vendorName: vendor.name, updatedBy: actor })
      return { vendorId: vendor.id, vendorName: vendor.name }
    },
    preview,
    async createDraft(id, input, actor) {
      if (!/^[a-f0-9]{64}$/.test(input.previewHash || '')) throw error('Preview the draft before creating it.')
      const sageClient = api()
      const expected = await preview(id, input.cogsType, sageClient)
      if (expected.hash !== input.previewHash) throw error('The invoice or vendor mapping changed. Review a fresh preview.', 409)
      const filter = entryFilter(id)
      const claim = await db().claimEntry(filter, { invoiceNumber: expected.invoiceNumber, vendorId: expected.vendor.id,
        cogsType: expected.cogsType, previewHash: expected.hash, createdBy: actor })
      if (!claim.claimed) {
        if (claim.entry?.status === 'created' && claim.entry.billKey) return { billKey: claim.entry.billKey, alreadyCreated: true, entityId: ENTITY, state: 'draft' }
        throw error('A creation attempt is in progress or its result is uncertain. Check Intacct before retrying.', 409)
      }
      let sent = false, billKey
      try {
        const existing = await sageClient.findBill(expected.vendor.id, expected.invoiceNumber)
        if (existing) throw error(`Invoice ${expected.invoiceNumber} already exists in Intacct. Review the existing bill instead.`, 409)
        sent = true
        billKey = await sageClient.createBill(buildBill(expected))
        await db().updateEntry(filter, { status: 'created', billKey })
        return { billKey, alreadyCreated: false, entityId: ENTITY, state: 'draft' }
      } catch (err) {
        const uncertain = sent && (!err.safeToRetry || billKey)
        await db().updateEntry(filter, { status: uncertain ? 'uncertain' : 'failed', ...(billKey ? { billKey } : {}) }).catch(() => {})
        if (billKey) throw error(`Intacct created draft ${billKey}, but Desk could not save its reference. Check Intacct before retrying.`, 502)
        if (uncertain) throw error('The Intacct creation result is uncertain. Check Intacct before retrying to avoid a duplicate bill.', 502)
        throw err
      }
    },
  }
}

module.exports = { buildPreview, buildBill, createIntegration }
