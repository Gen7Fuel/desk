const request = require('supertest')
const express = require('express')
const { getSettings } = require('./tradogram.settings')
const { resolveVendor } = require('./tradogram.vendor')
const service = require('./tradogram.service')
const { SiteAccount } = require('./tradogram.model')
const { authHeader } = require('../../tests/helpers/auth')
afterEach(() => { vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.unstubAllEnvs() })
it('defaults to test and rejects invalid company settings', () => {
  vi.stubEnv('TRADOGRAM_SAGE_ENTITY_ID', '')
  expect(getSettings()).toMatchObject({ entityId: 'T010', environment: 'test' })
  vi.stubEnv('TRADOGRAM_SAGE_ENTITY_ID', 'INVALID')
  expect(() => getSettings()).toThrow('must be T010')
})
it('queries the integration company without a site and ignores legacy site entities', async () => {
  vi.stubEnv('TRADOGRAM_SAGE_ENTITY_ID', 'T010')
  vi.stubEnv('SAGE_CLIENT_ID', 'id'); vi.stubEnv('SAGE_CLIENT_SECRET', 'secret')
  const fetch = vi.fn().mockResolvedValueOnce({ ok: true, json: async () => ({ access_token: 'token' }) })
    .mockResolvedValueOnce({ ok: true, json: async () => ({ 'ia::result': [{ id: 'V1', key: '1', status: 'active' }] }) })
  vi.stubGlobal('fetch', fetch)
  expect((await resolveVendor({ supplierAccountNumber: 'V1' }, { sageLocationId: 'A210' })).vendor.entityId).toBe('T010')
  expect(fetch.mock.calls[1][1].headers['X-IA-API-Param-Entity']).toBe('T010')
})
it('changing the integration company invalidates saved preparation fingerprints', () => {
  const source = { issues: [], supplierAccountNumber: 'V1', lines: [] }
  const config = { site: 'Construction', sageLocationId: 'A210' }
  vi.stubEnv('TRADOGRAM_SAGE_ENTITY_ID', 'T010')
  const test = service.prepare(source, { site: config.site }, config)
  expect(test.issues).toEqual([])
  vi.stubEnv('TRADOGRAM_SAGE_ENTITY_ID', 'A210')
  expect(getSettings()).toMatchObject({ company: 'Gen7 LP', environment: 'production' })
  expect(service.prepare(source, { site: config.site }, config).configHash).not.toBe(test.configHash)
})
it('exposes authenticated company settings and accepts construction sites independently of Hub', async () => {
  vi.stubEnv('TRADOGRAM_SAGE_ENTITY_ID', 'T010')
  const app = express().use(express.json()).use('/tradogram', require('./tradogram.routes'))
  expect((await request(app).get('/tradogram/settings')).status).toBe(401)
  const auth = authHeader({ permissions: { hub: { intacct: { read: true, update: true } } } })
  expect((await request(app).get('/tradogram/settings').set('Authorization', auth)).body.entityId).toBe('T010')
  const save = vi.spyOn(SiteAccount, 'findOneAndUpdate').mockImplementation(async (filter, update) => ({ ...filter, ...update.$set }))
  const result = await request(app).put('/tradogram/sites').set('Authorization', auth).send({ site: 'Future station construction', sageLocationId: 'A210' })
  expect(result.status).toBe(200)
  expect(result.body.site).toBe('Future station construction')
  expect(save.mock.calls[0][1].$set).not.toHaveProperty('sageLocationId')
})
